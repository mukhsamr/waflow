import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dir, '..');
const read = (path: string) => readFileSync(resolve(root, path), 'utf8');
const config = JSON.parse(read('wrangler.jsonc'));
const pkg = JSON.parse(read('package.json'));
assert.equal(config.name, 'waflow');
assert.deepEqual(config.observability, { enabled: true, head_sampling_rate: 1 });
assert.equal(config.account_id, undefined);
assert.equal(config.main, '.svelte-kit/cloudflare/_worker.js');
assert.equal(config.assets.binding, 'ASSETS');
assert.equal(config.assets.directory, '.svelte-kit/cloudflare');
assert.ok(existsSync(resolve(root, config.alias.ws)));
assert.equal(config.d1_databases[0].database_name, 'waflow-db');
assert.ok(readdirSync(resolve(root, config.d1_databases[0].migrations_dir)).includes('0008_gateway_events.sql'));
assert.equal(config.durable_objects.bindings[0].class_name, 'WaSession');
assert.ok(config.migrations[0].new_sqlite_classes.includes('WaSession'));
assert.deepEqual(config.queues.producers.map((entry: { queue: string }) => entry.queue).sort(), ['waflow-incoming', 'waflow-outgoing']);
assert.deepEqual(config.queues.consumers.map((entry: { queue: string }) => entry.queue).sort(), ['waflow-incoming', 'waflow-outgoing']);
assert.deepEqual(config.queues.consumers.map((entry: { dead_letter_queue: string }) => entry.dead_letter_queue).sort(), ['waflow-incoming-failed', 'waflow-outgoing-failed']);
assert.equal(pkg.workspaces, undefined);
assert.equal(pkg.scripts.deploy, 'bun scripts/deploy.ts');
assert.equal(config.vars.ADMIN_EMAIL, 'admin@nqmcreative.com');
assert.equal(config.vars.ADMIN_NAME, 'operator');
assert.deepEqual(config.secrets.required, ['ADMIN_PASSWORD']);
assert.equal(pkg.cloudflare, undefined);
assert.deepEqual(read('.dev.vars.example').trim().split(/\r?\n/).map((line) => line.split('=')), config.secrets.required.map((name: string) => [name, '']));
assert.ok(!Object.hasOwn(config.vars, 'API_URL'));
assert.ok(read('.gitignore').split(/\r?\n/).includes('.dev.vars'));
const readme = read('README.md');
const badge = readme.match(/\[!\[Deploy to Cloudflare\]\(https:\/\/deploy\.workers\.cloudflare\.com\/button\)\]\(([^)]+)\)/);
assert.ok(badge);
const url = new URL(badge[1]);
assert.equal(url.origin, 'https://deploy.workers.cloudflare.com');
assert.equal(url.searchParams.get('url'), 'https://github.com/mukhsamr/waflow');
assert.ok(!readme.includes('deploy:dashboard'));
console.log('Single Worker, resources, secrets, and deploy button checks passed.');
